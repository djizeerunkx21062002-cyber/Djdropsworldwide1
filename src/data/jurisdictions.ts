export function calculateTaxBreakdown(
  subtotalUsd: number,
  jurisdictionCode: string,
  taxId?: string
) {
  const j = findJurisdiction(jurisdictionCode);
  const cleanTaxId = (taxId || '').trim();
  const reverseChargeApplied = Boolean(j.reverseChargeEligible && cleanTaxId.length >= 6);
  const effectiveTaxRate = reverseChargeApplied ? 0 : j.taxRate;
  const taxAmountUsd = Number((subtotalUsd * effectiveTaxRate).toFixed(2));
  const totalUsd = Number((subtotalUsd + taxAmountUsd).toFixed(2));
  const localTotal = Number((totalUsd * j.fxPerUsd).toFixed(j.currency === 'JPY' || j.currency === 'UGX' || j.currency === 'KRW' || j.currency === 'VND' || j.currency === 'IDR' ? 0 : 2));

  return {
    jurisdiction: j,
    subtotalUsd,
    taxRate: effectiveTaxRate,
    standardRate: j.taxRate,
    taxAmountUsd,
    totalUsd,
    reverseChargeApplied,
    localCurrency: j.currency,
    localTotal,
    taxType: j.taxType,
  };
}
